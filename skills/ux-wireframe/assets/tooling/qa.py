class Doc(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.hrefs: list[str] = []
        self.ids: set[str] = set()
        self.h1 = 0
        self.headings: list[tuple[int, str]] = []
        self.styles = 0
        self.imgs = 0
        self.stack: list[str] = []
        self.mismatch: list[str] = []
        self.text_len = 0
        self.sections: list[str | None] = []   # data-layout per <section>, in order
        self.section_attrs: list[dict] = []      # attributes of each <section>, in order
        self._grab: str | None = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if a.get("id"):
            self.ids.add(a["id"])
        if tag == "a" and a.get("href"):
            self.hrefs.append(a["href"])
        if tag == "form" and a.get("action"):      # search / booking pages are reached through forms
            self.hrefs.append(a["action"])
        if tag in ("button", "input") and a.get("formaction"):   # a submit that posts elsewhere (quiz "email me")
            self.hrefs.append(a["formaction"])
        if tag == "section":
            self.sections.append(a.get("data-layout"))
            self.section_attrs.append(a)
        if tag == "style":
            self.styles += 1
        if tag == "img":
            self.imgs += 1
        if tag == "h1":
            self.h1 += 1
        if tag in ("h1", "h2", "h3"):
            self._grab = tag
            self.headings.append((int(tag[1]), ""))
        if tag not in VOID:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        # <path …/> inside inline SVG icons: self-closed, never left open on the stack
        self.handle_starttag(tag, attrs)
        if tag not in VOID and self.stack and self.stack[-1] == tag:
            self.stack.pop()

    def handle_endtag(self, tag):
        if tag in ("h1", "h2", "h3"):
            self._grab = None
        if tag in VOID:
            return
        if self.stack and self.stack[-1] == tag:
            self.stack.pop()
        elif tag in self.stack:
            while self.stack and self.stack.pop() != tag:
                self.mismatch.append(tag)

    def handle_data(self, data):
        s = data.strip()
        if not s:
            return
        self.text_len += len(s)
        if self._grab and self.headings:
            lvl, cur = self.headings[-1]
            self.headings[-1] = (lvl, (cur + " " + s).strip())


def layout_catalogue() -> set[str] | None:
    """Backticked names in the first column of the 'Layout catalogue' table."""
    if not DESIGN.is_file():
        return None
    text = DESIGN.read_text(encoding="utf-8")
    m = re.search(r"^##[^\n]*Layout catalogue[^\n]*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return set()
    return set(re.findall(r"^\|\s*`([a-z0-9-]+)`", m.group(1), re.M))


def component_catalogue() -> set[str] | None:
    """Component names (first column) of the '§8c Component catalogue' table; None if absent."""
    if not DESIGN.is_file():
        return None
    text = DESIGN.read_text(encoding="utf-8")
    m = re.search(r"^#{2,4}[^\n]*Component catalogue[^\n]*\n(.*?)(?=^#{2,4} |\Z)", text, re.M | re.S)
    if not m:
        return None
    names = set()
    for row in re.findall(r"^\|([^|\n]+)\|", m.group(1), re.M):
        cell = row.strip().strip("`").strip()
        if cell and not re.fullmatch(r":?-+:?", cell) and ":" in cell:
            names.add(cell)
    return names


def is_base_css(text: str) -> bool:
    m = re.match(r"\s*/\*(.*?)\*/", text, re.S)
    return bool(m and "bem-lint: base" in m.group(1))


def authored_css(site: dict) -> list[Path]:
    """Stylesheets a person writes: every site.config.json css entry except the generated tokens.css and
    sections.css, plus the section sources assets/sections/*.css that build.py concatenates."""
    out = [ROOT / rel for rel in site.get("css", []) if rel not in (TOKENS_CSS, SECTIONS_CSS) and (ROOT / rel).is_file()]
    return out + sorted((ROOT / "assets" / "sections").glob("*.css"))


def bem_issues(site: dict) -> tuple[list[str], list[str]]:
    """Run the vendored bem_lint.py --prefix w- over the authored stylesheets and sources."""
    sys.path.insert(0, str(ROOT))
    try:
        import bem_lint
    except ImportError:
        return ["bem_lint.py missing next to qa.py — re-run init_wireframe.py"], []
    css = authored_css(site)
    srcs = [p for d in ("_pages", "_partials", "_templates") for p in sorted((ROOT / d).glob("*.html"))]
    base = {p.resolve() for p in css if is_base_css(p.read_text(encoding="utf-8"))}
    rep = bem_lint.run(css + srcs, base, set(), "w-")
    errs, warns = [], []
    for it in rep.items:
        f = it["file"]
        try:
            f = Path(f).resolve().relative_to(ROOT).as_posix()
        except ValueError:
            pass
        loc = f"{f}:{it['line']}" if it["line"] else f
        (errs if it["level"] == "error" else warns).append(f"bem {loc} [{it['rule']}] {it['message']}")
    return errs, warns


IGNORED_IN_TEMPLATES = re.compile(r"(?:is|has|pi)-")   # states and build.py's icon-name classes (pi-<icon>)


class SectionTrees(HTMLParser):
    """Every <section data-brx-template> of a page as a dict: name, mode, layout, tree, content, classes.
    tree = the class tree (tag, data-brx, classes; runs of identical siblings collapsed, so lists may differ in
    length); content = the section's markup with whitespace collapsed (mode "element" needs it identical);
    classes = every class used inside. State classes and icon-name classes (pi-*) are ignored."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.found: list[dict] = []
        self._stack: list[list] = []      # [signature, children] of open elements inside a template section
        self._meta: dict | None = None
        self._raw: list[str] = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if not self._stack and tag == "section" and a.get("data-brx-template"):
            self._meta = {"name": a["data-brx-template"], "mode": a.get("data-brx-template-mode") or "",
                          "layout": a.get("data-layout") or "", "classes": set()}
            self._raw = []
        if self._meta is None:
            return
        self._meta["classes"] |= set(self._classes(a))
        self._raw.append(self.get_starttag_text() or "")
        if tag in VOID:
            if self._stack:
                self._stack[-1][1].append(((tag, a.get("data-brx") or "", self._classes(a)), ()))
            return
        self._stack.append([(tag, a.get("data-brx") or "", self._classes(a)), []])

    def handle_startendtag(self, tag, attrs):
        if self._meta is None:
            return
        self._meta["classes"] |= set(self._classes(dict(attrs)))
        self._raw.append(self.get_starttag_text() or "")
        if self._stack:
            self._stack[-1][1].append(((tag, dict(attrs).get("data-brx") or "", self._classes(dict(attrs))), ()))

    def handle_endtag(self, tag):
        if self._meta is None:
            return
        self._raw.append(f"</{tag}>")
        if tag in VOID or not self._stack:
            return
        sig, kids = self._stack.pop()
        node = (sig, self._collapse(kids))
        if self._stack:
            self._stack[-1][1].append(node)
        else:
            content = re.sub(r"\s+", " ", "".join(self._raw)).strip()
            self.found.append({**self._meta, "tree": node, "content": content})
            self._meta = None

    def handle_data(self, data):
        if self._meta is not None:
            self._raw.append(data)

    def handle_entityref(self, name):
        self.handle_data(f"&{name};")

    def handle_charref(self, name):
        self.handle_data(f"&#{name};")

    @staticmethod
    def _classes(a: dict) -> tuple:
        return tuple(sorted(c for c in (a.get("class") or "").split() if not IGNORED_IN_TEMPLATES.match(c)))

    @staticmethod
    def _collapse(kids: list) -> tuple:
        out: list = []
        for k in kids:
            if not out or out[-1] != k:
                out.append(k)
        return tuple(out)


def structure_diff(a: tuple, b: tuple, path: str = "") -> str:
    """First difference between two class trees, as a readable path."""
    (sa, ka), (sb, kb) = a, b
    here = f"{path} > {sa[0]}" + ("." + ".".join(sa[2]) if sa[2] else "")
    if sa != sb:
        return f"{here.strip(' >')} vs <{sb[0]}{' class=' + ' '.join(sb[2]) if sb[2] else ''}>"
    for x, y in zip(ka, kb):
        d = structure_diff(x, y, here)
        if d:
            return d
    if len(ka) != len(kb):
        return f"{here.strip(' >')}: {len(ka)} vs {len(kb)} kinds of children"
    return ""


def _norm(s: str) -> str:
    s = html.unescape(re.sub(r"<[^>]+>", " ", s)).lower().replace("\u2019", "'")
    return re.sub(r"[^\w]+", " ", s).strip()


def content_map() -> dict[str, str]:
    """page.html -> normalised text of the content file(s) that name it in their header block
    (the lines before the first '## ', e.g. '> Page: … · Wireframe: `about.html`')."""
    out: dict[str, list[str]] = {}
    if not CONTENT.is_dir():
        return {}
    for md in sorted(CONTENT.glob("*.md")):
        text = md.read_text(encoding="utf-8")
        head = text.split("\n## ", 1)[0]
        for line in head.splitlines():
            key = line.strip("> ").lower()
            if key.startswith(("page", "wireframe")) or "wireframe:" in key:
                for f in re.findall(r"([\w-]+\.html)\b", line):
                    out.setdefault(f, []).append(_norm(text))
    return {k: " ".join(v) for k, v in out.items()}



class TopLevel(HTMLParser):
    """Elements at depth 0 of a page fragment: [(tag, attrs)] — '#text' for loose text."""
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.depth = 0
        self.items: list[tuple[str, dict]] = []

    def handle_starttag(self, tag, attrs):
        if self.depth == 0:
            self.items.append((tag, dict(attrs)))
        if tag not in VOID:
            self.depth += 1

    def handle_startendtag(self, tag, attrs):
        if self.depth == 0:
            self.items.append((tag, dict(attrs)))

    def handle_endtag(self, tag):
        if tag not in VOID:
            self.depth = max(0, self.depth - 1)

    def handle_data(self, data):
        if self.depth == 0 and data.strip():
            self.items.append(("#text", {"text": data.strip()[:30]}))


def declaration_issues(css: str) -> list[str]:
    """Spacing off the 4 px grid, literal type sizes, text in content: — one line per declaration."""
    out = []
    for prop, value in DECL.findall(CSS_COMMENT.sub("", css)):
        value = value.strip()
        if prop == "content":
            if value not in ('""', "''", "none", "normal"):
                out.append(f"content: {value[:24]} (text in CSS is invisible to the design tool — put it in markup)")
            continue
        bare = VAR_CALL.sub("", value)
        if prop in ("font-size", "line-height", "font"):
            if prop == "font":
                bare = re.sub(r"\b[1-9]00\b", "", bare)      # weights are fine in the shorthand
            if value not in ("0", "inherit", "initial", "unset") and re.search(r"\d", bare):
                out.append(f"{prop}: {value[:32]} (use the type tokens var(--text-<step>) / var(--line-height-<step>))")
            continue
        for num, unit in SPACING_LITERAL.findall(bare):
            if unit != "px" or float(num) % 4:
                out.append(f"{prop}: {value[:32]} ({num}{unit} is off the 4 px spacing grid)")
                break
    return out


def breakpoints() -> dict[str, set[int]] | None:
    """Bricks breakpoints from handoff/bricks-tokens.json: max-width = width, min-width = width + 1."""
    if not TOKENS_JSON.is_file():
        return None
    bps = json.loads(TOKENS_JSON.read_text(encoding="utf-8")).get("breakpoints", [])
    return {"max": {b["width"] for b in bps}, "min": {b["width"] + 1 for b in bps}}


def token_issues(css: str, tokens: set[str], scoped: set[str], bps: dict[str, set[int]] | None) -> list[str]:
    """One token source: no custom property defined in a :root / html rule outside tokens.css; every
    token-family var() is a tokens.css name (or set by a scoped rule); @media only at the Bricks breakpoints."""
    out = []
    bare = CSS_COMMENT.sub("", css)
    for selector, body in CSS_RULE.findall(bare):
        if not any(ROOT_SELECTOR.match(s.strip()) for s in selector.split(",")):
            continue
        for name, value in TOKEN_DEF.findall(body):
            where = "is a token" if name in tokens else "is not in tokens.py"
            out.append(f"{selector.strip()} {{ {name}: {value.strip()[:24]} }} — {name} {where}; tokens are "
                       "defined only in tokens.py → assets/tokens.css (a [data-surface] rule may re-point them)")
    for name in sorted(set(TOKEN_REF.findall(bare))):
        if name not in tokens and name not in scoped and TOKEN_FAMILY.match(name):
            out.append(f"var({name}) is not a token in assets/tokens.css (renamed or removed? see tokens.py)")
    if bps:
        for query in re.findall(r"@media[^{]*", bare):
            for kind, width in MEDIA_WIDTH.findall(query):
                if int(width) not in bps[kind]:
                    out.append(f"@media ({kind}-width: {width}px) is not a Bricks breakpoint "
                               f"({kind}-width {' / '.join(map(str, sorted(bps[kind], reverse=True)))} px)")
    return out


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")   # Windows consoles default to cp1252
    cfg = dict(DEFAULTS)
    if CONFIG.is_file():
        cfg.update(json.loads(CONFIG.read_text(encoding="utf-8")))
    site = json.loads(SITE.read_text(encoding="utf-8")) if SITE.is_file() else {}
    archetype = site.get("archetype")

    built = sorted(ROOT.glob("*.html"))
    if not built:
        print("error: no built pages found — run build.py first", file=sys.stderr)
        return 1
    real = {p.name for p in built}

    docs: dict[str, Doc] = {}
    raws: dict[str, str] = {}
    for f in built:
        raws[f.name] = f.read_text(encoding="utf-8")
        d = Doc()
        d.feed(raws[f.name])
        docs[f.name] = d

    problems: list[str] = []
    warnings: list[str] = []
    missing_pages: Counter[str] = Counter()
    anchor_misses: list[str] = []

    if archetype not in ARCHETYPES:
        problems.append(f"site.config.json: archetype must be one of {sorted(ARCHETYPES)} "
                        f"(decided in phase 3), found {archetype!r}")

    for name, d in docs.items():
        raw = raws[name]
        if d.h1 != 1:
            problems.append(f"{name}: expected exactly 1 <h1>, found {d.h1}")
        if d.styles:
            problems.append(f"{name}: contains {d.styles} <style> block(s)")
        if d.imgs:
            problems.append(f"{name}: contains {d.imgs} <img> (image slots are .w-photo briefs)")
        if d.mismatch:
            problems.append(f"{name}: mismatched end tags {sorted(set(d.mismatch))}")
        if d.stack:
            problems.append(f"{name}: unclosed tags {d.stack}")

        prev = 1
        for lvl, txt in d.headings:
            if lvl > prev + 1:
                warnings.append(f"{name}: heading jump h{prev}->h{lvl} at \u201c{txt[:44]}\u201d")
            prev = lvl

        dup = [i for i, c in Counter(re.findall(r'\sid="([^"]+)"', raw)).items() if c > 1]
        if dup:
            problems.append(f"{name}: duplicate id(s) {dup}")

        for href in d.hrefs:
            if href.startswith(("http://", "https://", "tel:", "mailto:", "javascript:")):
                continue
            if href.startswith("#"):
                if href[1:] and href[1:] not in d.ids:
                    anchor_misses.append(f"{name} -> {href}")
                continue
            page, _, frag = href.partition("#")
            page = page.split("?", 1)[0]
            if not page:
                continue
            if page not in real:
                missing_pages[page] += 1
            elif frag and frag not in docs[page].ids:
                anchor_misses.append(f"{name} -> {href}")

        if "PLACEHOLDER" in raw:
            problems.append(f"{name}: contains PLACEHOLDER text")
        if re.search(r'class="[^"]*\bw-(?:anno|sec-id)\b', raw):
            problems.append(f"{name}: contains review annotations (.w-anno / .w-sec-id)")
        text = re.sub(r"<!--.*?-->|<script.*?</script>|<[^>]+>", " ", raw, flags=re.S).lower()
        notes = [n for n in REVIEW_NOTES if re.search(r"\b" + re.escape(n), text)]
        if 'id="stub-' in raw:
            notes.append("stub page")
        if notes:
            problems.append(f"{name}: review/authoring notes on the page {notes} — build the real page")
        voice = [p for p in META_VOICE + cfg["meta_phrases"] if p.lower() in text]
        if voice:
            warnings.append(f"{name}: author/AI voice in copy {voice} — rewrite for the reader")
        # image slots carry their art direction inside the .w-photo; a visible caption/note next to
        # the image ("Wound-care nurse · home visit", "In-vitro results.") reads as leftover notes
        visible_raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)
        captions = len(re.findall(r'<\w+[^>]*class="[^"]*\b(?:caption|figure-note|img-note)\b[^"]*"', visible_raw))
        captions += sum(1 for fig in re.findall(r"<figure\b[^>]*>(.*?)</figure>", visible_raw, re.S)
                        if re.search(r'class="[^"]*\bw-photo\b', fig) and "<figcaption" in fig)
        if captions:
            warnings.append(f"{name}: {captions} visible caption(s)/note(s) on image slots — "
                            "put role, setting and art direction inside the .w-photo brief instead")
        # banned terms are about copy a reader sees: visible text plus attributes that are read
        # (alt, aria-label, title, placeholder, meta content, filter/result labels, form messages).
        # URLs, ids, classes and search synonyms (data-keywords) may hold the plain form ("zrce").
        readable = text + " " + " ".join(re.findall(
            r'\s(?:alt|aria-label|title|placeholder|content|data-label|data-result-label[\w-]*|data-demo-form)="([^"]*)"', raw))
        for term in cfg["banned_terms"]:
            if re.search(r"\b" + re.escape(term) + r"\w*", readable, flags=re.I):
                problems.append(f"{name}: banned term \u201c{term}\u201d")
        if cfg["banned_chars"] and re.search("[" + cfg["banned_chars"] + "]", raw):
            problems.append(f"{name}: authoring note in the wrong language")

        if archetype == "commerce":
            cur = cfg["currency"]
            for m in re.finditer(r"<(p|div|span)[^>]*class=\"[^\"]*w-card-product__price[^\"]*\"[^>]*>(.*?)</\1>", raw, re.S):
                inner = re.sub(r"<[^>]+>", "", m.group(2)).strip()
                if cur and cur not in inner:
                    problems.append(f"{name}: empty .w-card-product__price -> \u201c{inner[:40]}\u201d")
        elif archetype:
            leaked = [t for t in COMMERCE_ONLY if t in raw]
            if leaked:
                problems.append(f"{name}: commerce-only markup on a {archetype} site {leaked}")

    # ---- composition: detailed pages must trace every section to design-direction.md
    catalogue = layout_catalogue()
    sheets = {p.stem for p in (ROOT / "assets" / "sections").glob("*.css")}
    detailed = list(docs)          # every built page is a real page: no stub exemption
    sequences: dict[str, tuple] = {}
    if catalogue is None:
        problems.append("design-direction.md missing next to wireframe/ (phase 3 output)")
        catalogue = set()
    elif not catalogue:
        problems.append("design-direction.md has no '## … Layout catalogue' table with `layout-name` rows")
    for name in detailed:
        seq = docs[name].sections
        if not seq:
            problems.append(f"{name}: no <section> elements")
            continue
        unnamed = sum(1 for s in seq if not s)
        if unnamed:
            problems.append(f"{name}: {unnamed} <section>(s) without data-layout")
        named = [s for s in seq if s]
        for lay, a in zip(seq, docs[name].section_attrs):
            if not lay:
                continue
            if f"w-{lay}" not in (a.get("class") or "").split():
                problems.append(f"{name}: section data-layout \u201c{lay}\u201d lacks class \u201cw-{lay}\u201d "
                                f"— write <section class=\"w-{lay}\" data-layout=\"{lay}\" data-brx=\"section\" …>")
            if a.get("data-brx") != "section":
                problems.append(f"{name}: section data-layout \u201c{lay}\u201d lacks data-brx=\"section\" "
                                "(Bricks Section > Container > Block/Div)")
        for lay in sorted(set(named)):
            if lay not in catalogue:
                problems.append(f"{name}: data-layout \u201c{lay}\u201d not defined in design-direction.md")
            if lay not in sheets:
                problems.append(f"{name}: data-layout \u201c{lay}\u201d has no stylesheet assets/sections/{lay}.css")
        for a, b in zip(named, named[1:]):
            if a == b:
                problems.append(f"{name}: consecutive sections share layout \u201c{a}\u201d")
        if named and len(set(named)) / len(named) < cfg["min_layout_variety"]:
            warnings.append(f"{name}: low layout variety {len(set(named))}/{len(named)}")
        sequences[name] = tuple(named)
    seen: dict[tuple, str] = {}
    for name, seq in sequences.items():
        if GENERATED.search(raws[name]):
            continue               # a generated family shares its template's skeleton by design
        if len(seq) > 2 and seq in seen:
            warnings.append(f"{name}: same section skeleton as {seen[seq]} — pages are cloned")
        seen.setdefault(seq, name)

    # ---- Bricks Section templates (class-system.md §8). Mode "element": one structure and one content everywhere.
    # Mode "insert": same section and container classes (the top two levels); inside, an instance may leave out
    # optional parts, vary list lengths, icons and per-instance modifiers — but every element class of a section
    # block it uses belongs to its own block, and a section-element class that only one instance uses and the
    # section's stylesheet never mentions is reported (probably a typo).
    instances: dict[str, list[dict]] = {}
    for name in docs:
        st = SectionTrees()
        st.feed(raws[name])
        for inst in st.found:
            instances.setdefault(inst["name"], []).append({**inst, "page": name})
    section_blocks = {f"w-{lay}" for d in docs.values() for lay in d.sections if lay}
    block_of = lambda c: c.split("__")[0].split("--")[0]
    for tpl, found in sorted(instances.items()):
        modes = {i["mode"] for i in found}
        bad_modes = sorted(m or "(none)" for m in modes - {"element", "insert"})
        if bad_modes:
            problems.append(f"template \u201c{tpl}\u201d: data-brx-template-mode {bad_modes} — use element "
                            "(same structure and content) or insert (same classes, own content)")
        if len(modes) > 1:
            problems.append(f"template \u201c{tpl}\u201d: mixed modes {sorted(modes)} on {sorted({i['page'] for i in found})}")
        first = found[0]
        top = lambda i: (i["tree"][0], tuple(sorted({k[0] for k in i["tree"][1]})))
        for inst in found[1:]:
            if inst["mode"] == "element" and inst["tree"] != first["tree"]:
                problems.append(f"template \u201c{tpl}\u201d (mode element): {inst['page']} differs in class structure from "
                                f"{first['page']} ({structure_diff(inst['tree'], first['tree'])}) — a Template element "
                                "has one structure everywhere")
            elif inst["mode"] == "element" and inst["content"] != first["content"]:
                problems.append(f"template \u201c{tpl}\u201d (mode element): {inst['page']} differs in content from "
                                f"{first['page']} — a Template element shows one content everywhere; use mode insert for own copy")
            elif inst["mode"] != "element" and top(inst) != top(first):
                problems.append(f"template \u201c{tpl}\u201d: {inst['page']} differs in class structure from {first['page']} "
                                f"(section / container classes {' '.join(top(inst)[0][2])} | "
                                f"{', '.join(' '.join(k[2]) for k in top(inst)[1])} vs {' '.join(top(first)[0][2])} | "
                                f"{', '.join(' '.join(k[2]) for k in top(first)[1])}) — every instance of a Bricks "
                                "template has the same section and container classes")
        for inst in found:
            own = f"w-{inst['layout']}" if inst["layout"] else block_of(inst["tree"][0][2][0]) if inst["tree"][0][2] else ""
            foreign = sorted(c for c in inst["classes"] if "__" in c and block_of(c) in section_blocks and block_of(c) != own)
            if foreign:
                problems.append(f"template \u201c{tpl}\u201d: {inst['page']} uses another section's element class(es) "
                                f"{', '.join(foreign)} inside {own} — a template carries only its own block and components")
        if len(found) > 1 and found[0]["layout"]:
            sheet = ROOT / "assets" / "sections" / f"{found[0]['layout']}.css"
            sheet_text = CSS_COMMENT.sub("", sheet.read_text(encoding="utf-8")) if sheet.is_file() else ""
            own = f"w-{found[0]['layout']}__"
            for inst in found:
                others = set().union(*(o["classes"] for o in found if o is not inst))
                lone = sorted(c for c in inst["classes"] if c.startswith(own) and c not in others
                              and not re.search(r"\." + re.escape(c) + r"(?![\w-])", sheet_text))
                if lone:
                    problems.append(f"template \u201c{tpl}\u201d: {inst['page']} uses {', '.join(lone)} — no other instance "
                                    f"uses it and assets/sections/{found[0]['layout']}.css never styles it (a typo?)")

    # navigation reachability: a link present on every page lives in the header or footer.
    # Every authored page must be one of those targets (generated families are reached via listings).
    # Flow pages say how they are reached in their META instead of sitting in the navigation:
    #   "flow": "form"   — reached through a form or a CTA (search results, booking, confirmation)
    #   "flow": "server" — served by the web server, never linked (404, 500)
    def flow_of(name: str) -> str:
        frag = ROOT / "_pages" / name
        m = META_RE_QA.match(frag.read_text(encoding="utf-8")) if frag.is_file() else None
        try:
            return str(json.loads(m.group(0)[len("<!--META"):-len("-->")]).get("flow", "")) if m else ""
        except json.JSONDecodeError:
            return ""
    flows = {name: flow_of(name) for name in docs}
    page_links = [{h.split("#")[0].split("?")[0] for h in d.hrefs
                   if not h.startswith(("http", "tel:", "mailto:", "#", "javascript:"))}
                  for d in docs.values()]
    global_nav = set.intersection(*page_links) if page_links else set()
    for name in docs:
        if name == "index.html" or GENERATED.search(raws[name]) or flows[name]:
            continue
        if name not in global_nav:
            warnings.append(f"{name}: not linked from the header or footer — add it to the navigation "
                            '(or declare META "flow": "form" / "server" for a flow page)')

    # every page except home must be reachable from at least one other page (links or form actions)
    linked_from: Counter[str] = Counter()
    for name, links in zip(docs, page_links):
        for target in links - {name}:
            linked_from[target] += 1
    for name in docs:
        if name != "index.html" and flows[name] != "server" and not linked_from[name]:
            problems.append(f"{name}: orphan page — no other page links to it")

    # drift: fragments must agree with their content files (fix the source first, then the page)
    cmap = content_map()
    if cmap:
        for name in docs:
            if GENERATED.search(raws[name]):
                continue
            frag = ROOT / "_pages" / name
            if name not in cmap:
                warnings.append(f"{name}: no content/*.md names this page in its header block")
                continue
            if not frag.is_file():
                continue
            for lvl, inner in re.findall(r"<h([12])\b[^>]*>(.*?)</h\1>",
                                         frag.read_text(encoding="utf-8"), re.S):
                h = _norm(inner)
                if h and h not in cmap[name]:
                    warnings.append(f"{name}: h{lvl} \u201c{h[:50]}\u201d is not in its content file "
                                    "— update content/*.md (source first)")

    # ---- stylesheet stack: tokens.css → base.css → components.css → sections.css (generated from assets/sections/)
    stack = site.get("css", [])
    for rel in stack:
        if rel.startswith(OBSOLETE_CSS):
            problems.append(f"site.config.json css lists {rel} — that layer is gone: components live in "
                            "assets/components.css, section layouts and skins in assets/sections/<layout>.css")
    want = [TOKENS_CSS, "assets/base.css", "assets/components.css", SECTIONS_CSS]
    if [rel for rel in stack if rel in want] != want:
        problems.append(f"site.config.json css must load {' → '.join(want)} in this order (found {stack})")

    # ---- design-tool contract: what html-to-figma reads (handoff.py builds on it)
    # tokens.css (token names) + every authored stylesheet; sections.css is checked through its sources
    all_css: dict[str, str] = {}
    for p in ([ROOT / TOKENS_CSS] if (ROOT / TOKENS_CSS).is_file() and TOKENS_CSS in stack else []) + authored_css(site):
        all_css[p.relative_to(ROOT).as_posix()] = p.read_text(encoding="utf-8")
    surfaces = {"default"} | {s for css_text in all_css.values()
                              for s in re.findall(r'\[data-surface="([\w-]+)"\]', css_text)}
    # ---- tokens: one source (tokens.py → assets/tokens.css, the Bricks Style Manager mirror)
    token_path = ROOT / TOKENS_CSS
    tokens: set[str] = set()
    if TOKENS_CSS not in all_css or not token_path.is_file():
        problems.append(f"{TOKENS_CSS} missing or not in site.config.json css — run python tokens.py "
                        f"and list {TOKENS_CSS} first")
    else:
        tokens = {n for n, _ in TOKEN_DEF.findall(CSS_COMMENT.sub("", all_css[TOKENS_CSS]))}
        if stack[:1] != [TOKENS_CSS]:
            problems.append(f"{TOKENS_CSS} must load first (site.config.json css)")
    bps = breakpoints()
    if bps is None:
        problems.append("handoff/bricks-tokens.json missing — run python tokens.py")
    scoped = {n for rel, css_text in all_css.items() if rel != TOKENS_CSS
              for sel, body in CSS_RULE.findall(CSS_COMMENT.sub("", css_text))
              if not any(ROOT_SELECTOR.match(s.strip()) for s in sel.split(","))
              for n, _ in TOKEN_DEF.findall(body)}
    for rel, css_text in all_css.items():
        if rel == TOKENS_CSS:
            continue          # generated and validated by tokens_builder.py
        for issue in (declaration_issues(css_text) + token_issues(css_text, tokens, scoped, bps))[:12]:
            problems.append(f"{rel}: {issue}")
        gone = sorted({c for sel, _ in CSS_RULE.findall(CSS_COMMENT.sub("", css_text))
                       for c in re.findall(r"\.(-?[_a-zA-Z][\w-]*)", re.sub(r"\[[^\]]*\]", "", sel))
                       if REMOVED_PRIMITIVE.match(c)})
        if gone:
            problems.append(f"{rel}: removed layout primitive(s) {', '.join('.' + c for c in gone)} — {REMOVED_HINT}")
        if "[data-layout" in CSS_COMMENT.sub("", css_text):
            problems.append(f"{rel}: [data-layout] selector — style the section's block class .w-<layout> "
                            "(data-layout is metadata only)")
    sources = sorted((ROOT / "_pages").glob("*.html")) + sorted((ROOT / "_partials").glob("*.html"))
    templates = sorted((ROOT / "_templates").glob("*.html"))
    used_components: Counter[str] = Counter()
    for src in sources + templates:
        for comp in re.findall(r'\sdata-component="([^"]+)"', src.read_text(encoding="utf-8")):
            used_components[comp] += 1
    comp_cat = component_catalogue()
    if comp_cat is not None:
        for comp in sorted(set(used_components) - comp_cat):
            problems.append(f"data-component \u201c{comp}\u201d ({used_components[comp]}x) is not in "
                            "design-direction.md §8c Component catalogue — add it or reuse a listed one")
        for comp in sorted(comp_cat - set(used_components)):
            warnings.append(f"component \u201c{comp}\u201d is in §8c Component catalogue but never used")
    elif used_components:
        warnings.append("data-component used but design-direction.md has no §8c Component catalogue table")
    bem_errs, bem_warns = bem_issues(site)
    problems += bem_errs
    warnings += bem_warns
    for src in sources + templates:
        rel = src.relative_to(ROOT).as_posix()
        text = src.read_text(encoding="utf-8")
        gone = sorted({c for attr in re.findall(r'\sclass="([^"]*)"', text) for c in attr.split()
                       if REMOVED_PRIMITIVE.match(c)})
        if gone:
            problems.append(f"{rel}: removed layout primitive(s) {', '.join(gone)} — {REMOVED_HINT}")
        if src in templates:
            continue
        for style_attr in re.findall(r'\sstyle="([^"]*)"', text):
            for issue in declaration_issues(style_attr)[:3]:
                problems.append(f"{rel}: inline style {issue}")
        if re.search(r'class="[^"]*\bwf-bar\b', text):
            problems.append(f"{rel}: review bar (wf-bar) above the site — delete it; the wireframe is "
                            "navigated through its own header and footer like the real site")
        if src.parent.name != "_pages":
            continue
        top = TopLevel()
        top.feed(META_RE_QA.sub("", text, count=1))
        for tag, attrs in top.items:
            if tag == "dialog":
                continue
            if tag != "section":
                what = f"text \u201c{attrs['text']}\u201d" if tag == "#text" else f"<{tag}>"
                problems.append(f"{rel}: stray top-level {what} — every top-level element is a "
                                "<section data-layout data-surface> or <dialog> (breadcrumb goes inside the first section)")
            elif attrs.get("data-surface") not in surfaces:
                problems.append(f"{rel}: section #{attrs.get('id', '?')} data-surface="
                                f"\u201c{attrs.get('data-surface')}\u201d — one of {sorted(surfaces)}")
    for name, raw in raws.items():
        visible = re.sub(r"<!--.*?-->|<script.*?</script>|<[^>]+>", " ", raw, flags=re.S)
        glyphs = sorted({ch for ch in visible if ch in ICON_GLYPHS})
        if glyphs:
            problems.append(f"{name}: icon glyph(s) {' '.join(glyphs)} in the page — use <i data-icon=\"…\"> "
                            "(assets/icons/)")
    if "index.html" in raws:
        for hook in ("nav", "footer-col"):
            if f'data-chrome="{hook}"' not in raws["index.html"]:
                warnings.append(f"header/footer: no data-chrome=\"{hook}\" hook — the design-tool handoff "
                                "reads navigation and footer columns from it")
    for name, hooks in cfg["required_hooks"].items():
        if name not in real:
            problems.append(f"{name}: required page missing from build")
            continue
        gone = [h for h in hooks if h not in raws[name]]
        if gone:
            problems.append(f"{name}: missing interaction hook(s) {gone}")

    bar = "=" * 68
    print(bar)
    generated = sum(1 for n in docs if GENERATED.search(raws[n]))
    print(f"PAGES BUILT: {len(built)}  (authored: {len(built) - generated}, generated: {generated}, "
          f"archetype: {archetype})")
    for f in built:
        d = docs[f.name]
        print(f"  {f.name:38} {f.stat().st_size // 1024:>4} KB  links={len(d.hrefs):>3}  "
              f"ids={len(d.ids):>3}  text={d.text_len:>6}")

    print("\n" + bar)
    print("COMPOSITION (all pages):")
    for name, seq in sequences.items():
        print(f"  {name}: {len(seq)} sections, {len(set(seq))} distinct layouts")
        print("    " + " > ".join(seq))
    if catalogue:
        used = {l for s in sequences.values() for l in s}
        unused = sorted(catalogue - used)
        print(f"  catalogue: {len(catalogue)} layouts, {len(used)} used"
              + (f", unused: {', '.join(unused)}" if unused else ""))

    print("\n" + bar)
    print("LINKS -> pages not present in the build:")
    for p, c in sorted(missing_pages.items(), key=lambda x: -x[1]) or []:
        print(f"  {p:38} referenced {c}x")
    if not missing_pages:
        print("  none")

    print("\n" + bar)
    if anchor_misses:
        print(f"BROKEN ANCHORS ({len(anchor_misses)}):")
        for a in sorted(set(anchor_misses)):
            print(f"  x {a}")
    else:
        print("BROKEN ANCHORS: none")

    print("\n" + bar)
    if problems:
        print(f"PROBLEMS ({len(problems)}):")
        for p in problems:
            print(f"  x {p}")
    else:
        print("PROBLEMS: none")
    if warnings:
        print(f"\nWARNINGS ({len(warnings)}):")
        for w in warnings[:25]:
            print(f"  ! {w}")
        if len(warnings) > 25:
            print(f"  ... {len(warnings) - 25} more")

    return 1 if (problems or anchor_misses or missing_pages) else 0


if __name__ == "__main__":
    raise SystemExit(main())
