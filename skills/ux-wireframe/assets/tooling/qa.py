#!/usr/bin/env python3
"""
QA gate for a wireframe build. Run after build.py; exit code 1 = blocking problem.

Checks
  structure   : exactly one <h1>, no <style>, no <img> (image slots are .w-photo), balanced tags, no duplicate id
  links       : every relative href resolves to a built page; every #anchor exists
  copy        : no review scaffolding (.w-anno, .w-sec-id, PLACEHOLDER), no banned terms/chars
  archetype   : site.config.json declares the archetype chosen in phase 3; commerce-only
                markup (prices, cart, favourites, filter rail, payment chips) is rejected on
                non-commerce sites; prices are checked only on commerce sites
  composition : on every detailed page each <section> carries data-layout="<name>", the class w-<name> (the
                section's own BEM block) and data-brx="section"; the name is defined in design-direction.md
                §Layout catalogue and has its own stylesheet assets/sections/<name>.css (build.py concatenates
                them into assets/sections.css); no two consecutive sections share a layout; low layout
                variety and cloned page skeletons are reported
  templates   : sections sharing a data-brx-template name (a Bricks Section template): mode "element" = identical
                class structure and content; mode "insert" = same section and container classes, no other
                section's element classes inside, and a section-element class only one instance uses must be
                styled in assets/sections/<layout>.css (else: a typo?); pi-* / is-* / has-* classes are ignored
  bem         : bem_lint.py --prefix w- (skill bricks-bem-html) over base.css, components.css, every other
                authored stylesheet of site.config.json, assets/sections/*.css and the authored sources
                (_pages, _partials, _templates): lint errors fail, warnings warn
  primitives  : no shared layout class (w-layout-*, section, wrap, cols, span-N, split*, grid, g-N, row, stack,
                bento …) in markup or CSS — sections own their layout; site.config.json css is tokens.css,
                base.css, components.css, sections.css (no wireframe.css / packs / site.css / style.css layer)
  components  : with a design-direction.md §8c Component catalogue, every data-component
                used in the sources is listed there; unused catalogue entries warn
  hooks       : pages declare the interaction attributes their design needs
  copy voice  : warnings for author/AI voice, captions next to image slots
  drift       : every authored page has a content/*.md naming it in its header block, and
                every h1/h2 of the fragment appears in that file (sources stay the truth)
  reach       : authored pages are in the header/footer; every page is linked from another (links and
                form actions and submit formactions count); flow pages declare META "flow": "form" | "server" instead
  handoff     : (design-tool contract, html-to-figma) every top-level element of a fragment is a
                <section data-layout data-surface> or <dialog>; spacing literals in stylesheets
                and inline styles sit on the 4 px grid; font-size / line-height use type tokens
                (var(--text-<step>) / var(--line-height-<step>)); no text in CSS content:; no glyph
                icons in copy (use <i data-icon>); header/footer carry
                data-chrome hooks; no review bar (wf-bar) in partials or pages
  tokens      : assets/tokens.css (generated by tokens.py) exists and loads first; no stylesheet
                defines a custom property in a :root / html rule (tokens live only in tokens.py;
                [data-surface] rules may re-point them); every token-family var() is defined in
                tokens.css (or by a scoped rule); @media widths only at the Bricks breakpoints of
                handoff/bricks-tokens.json (max-width = width, min-width = width + 1)

Config: wireframe/qa.config.json
{ "currency": "€", "banned_terms": [...], "banned_chars": "...",
  "required_hooks": { "index.html": ["data-slider"] } }
"""
