#!/usr/bin/env python3
"""
Wireframe builder.

    python wireframe/build.py            # review build (keeps optional <!--wf:review--> blocks)
    python wireframe/build.py --final    # handoff build: strips <!--wf:review-->…<!--/wf:review--> blocks

Input : wireframe/_pages/*.html     body fragments, line 1 = JSON meta comment
        wireframe/_partials/header.html, footer.html
        wireframe/site.config.json  {"archetype": "...", "css": ["assets/tokens.css", "assets/base.css",
                                     "assets/components.css", "assets/sections.css"], "style": true}
                                     # "style": true once the UI refine (phase 7) has skinned the components
        wireframe/assets/sections/*.css  one stylesheet per section block (<layout>.css) + header.css / footer.css
        wireframe/handoff/bricks-tokens.json  styleManager.defaultMode (written by tokens.py)
        wireframe/i18n.json         optional engine strings, sets <html lang>
        wireframe/assets/icons/*.svg icon library (Phosphor regular, 256 viewBox)
Output: wireframe/*.html            standalone pages, openable with file://
        wireframe/assets/sections.css  GENERATED: assets/sections/*.css concatenated (header first, footer
                                     last, the other sections alphabetically) — never edit it

Meta comment on line 1 of each fragment:
<!--META {"title":"...","desc":"...","template":"T:home","nav":"home","body_class":""} -->

Icons: <i data-icon="arrow-right" class="w-icon w-icon--small"></i> in fragments and partials becomes
<svg class="w-icon pi-arrow-right w-icon--small" viewBox="0 0 256 256" aria-hidden="true" focusable="false">…</svg>.
The source names the `w-icon` block next to its modifiers (BEM gate); `w-icon` is never doubled.
With aria-label="…" on the <i>, the svg gets role="img" and that label instead of aria-hidden.
An unknown icon name stops the build.

Stylesheets load in config order (class system: skill bricks-bem-html references/class-system.md):
  assets/tokens.css      generated by tokens.py — the Bricks Style Manager mirror, the ONLY place a token is defined
  assets/base.css        theme style: reset, tag typography, surfaces, Bricks element defaults for data-brx
                         (the only stylesheet with tag selectors)
  assets/components.css  every reused class (w-button-*, w-heading-*, w-card-*, w-photo, w-icon …), skins included
  assets/sections.css    generated here from assets/sections/*.css (one file per section block w-<layout>)
"style": true sets <html data-style="on"> (UI refine done: the browser probe stops enforcing grayscale).
Every asset URL carries ?v=<mtime> so browser QA never reads a stale file.

Dark mode is Bricks' own: a one-line <head> script sets <html data-brx-theme="light|dark"> before
first paint from localStorage "brx_mode", else from the Style Manager default mode in
handoff/bricks-tokens.json ("auto" = prefers-color-scheme); tokens.css holds every dark value.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = ROOT / "_pages"
PARTIALS = ROOT / "_partials"
ICONS = ROOT / "assets" / "icons"
CONFIG = ROOT / "site.config.json"
TOKENS_JSON = ROOT / "handoff" / "bricks-tokens.json"
DEFAULT_CSS = ["assets/tokens.css", "assets/base.css", "assets/components.css", "assets/sections.css"]
SECTIONS_DIR = ROOT / "assets" / "sections"
SECTIONS_CSS = ROOT / "assets" / "sections.css"
SECTIONS_FIRST, SECTIONS_LAST = ["header"], ["footer"]

DOC = """<!DOCTYPE html>
<html lang="{lang}"{style}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{desc}">
<script>try{{var m=localStorage.getItem("brx_mode")||"{mode}";document.documentElement.dataset.brxTheme=m==="auto"?(matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light"):m}}catch(e){{}}</script>
{css}
</head>
<body data-nav="{nav}" data-template="{template}"{body_class}>
{header}
{body}
{footer}
{i18n}<script src="assets/wireframe.js?v={jsv}"></script>
</body>
</html>
"""

META_RE = re.compile(r"^<!--META\s*(\{.*?\})\s*-->\s*", re.DOTALL)
REVIEW_RE = re.compile(r"[ \t]*<!--wf:review-->.*?<!--/wf:review-->[ \t]*\n?", re.DOTALL)
ICON_RE = re.compile(r"<i\b([^>]*\bdata-icon=\"([\w-]+)\"[^>]*)>\s*</i>")
ATTR_RE = re.compile(r'([\w-]+)="([^"]*)"')
SVG_RE = re.compile(r"<svg\b([^>]*)>(.*)</svg>", re.DOTALL)
_icon_cache: dict[str, tuple[str, str]] = {}


class BuildError(Exception):
    pass


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def mtime(rel: str) -> str:
    p = ROOT / rel
    if not p.is_file():
        raise BuildError(f"stylesheet/script {rel} listed in site.config.json does not exist")
    return str(int(p.stat().st_mtime))


def icon_svg(name: str) -> tuple[str, str]:
    """(viewBox, inner markup) of assets/icons/<name>.svg."""
    if name not in _icon_cache:
        f = ICONS / f"{name}.svg"
        if not f.is_file():
            known = ", ".join(sorted(p.stem for p in ICONS.glob("*.svg"))) if ICONS.is_dir() else "(no assets/icons/)"
            raise BuildError(f"unknown icon \u201c{name}\u201d — add assets/icons/{name}.svg or use one of: {known}")
        m = SVG_RE.search(f.read_text(encoding="utf-8"))
        if not m:
            raise BuildError(f"assets/icons/{name}.svg is not an <svg> file")
        vb = re.search(r'viewBox="([^"]+)"', m.group(1))
        _icon_cache[name] = (vb.group(1) if vb else "0 0 256 256", m.group(2).strip())
    return _icon_cache[name]


def expand_icons(html: str, where: str) -> str:
    def sub(m: re.Match) -> str:
        attrs = dict(ATTR_RE.findall(m.group(1)))
        name = m.group(2)
        try:
            vb, inner = icon_svg(name)
        except BuildError as e:
            raise BuildError(f"{where}: {e}") from None
        cls = " ".join(dict.fromkeys(["w-icon", f"pi-{name}", *attrs.get("class", "").split()]))
        label = attrs.get("aria-label")
        a11y = f'role="img" aria-label="{esc(label)}"' if label else 'aria-hidden="true"'
        return f'<svg class="{cls}" viewBox="{vb}" {a11y} focusable="false">{inner}</svg>'
    return ICON_RE.sub(sub, html)


def build_sections_css() -> None:
    """assets/sections.css = assets/sections/*.css concatenated: header first, footer last, the other
    sections alphabetically. Rewritten only when its content changes (keeps the ?v= stamp stable)."""
    if not SECTIONS_DIR.is_dir():
        raise BuildError("assets/sections/ is missing (one stylesheet per section block: <layout>.css, header.css, footer.css)")
    files = {p.stem: p for p in SECTIONS_DIR.glob("*.css")}
    edge = SECTIONS_FIRST + SECTIONS_LAST
    order = ([n for n in SECTIONS_FIRST if n in files] + sorted(n for n in files if n not in edge)
             + [n for n in SECTIONS_LAST if n in files])
    parts = ["/* GENERATED by build.py from assets/sections/*.css (header first, footer last, the other sections\n"
             "   alphabetically). Never edit this file: change the section's own stylesheet and rebuild. */\n"]
    for name in order:
        parts.append(f"/* ====================== assets/sections/{name}.css ====================== */\n"
                     + files[name].read_text(encoding="utf-8").strip() + "\n")
    text = "\n".join(parts)
    if not SECTIONS_CSS.is_file() or SECTIONS_CSS.read_text(encoding="utf-8") != text:
        with open(SECTIONS_CSS, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)


def build(final: bool) -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if not PAGES.is_dir():
        print("error: missing _pages/", file=sys.stderr)
        return 1
    header_tpl = (PARTIALS / "header.html").read_text(encoding="utf-8")
    footer = (PARTIALS / "footer.html").read_text(encoding="utf-8")
    if final:
        header_tpl = REVIEW_RE.sub("", header_tpl)
        footer = REVIEW_RE.sub("", footer)

    cfg = json.loads(CONFIG.read_text(encoding="utf-8")) if CONFIG.is_file() else {}
    try:
        build_sections_css()
        css = "\n".join(
            f'<link rel="stylesheet" href="{rel}?v={mtime(rel)}">' for rel in cfg.get("css", DEFAULT_CSS)
        )
        jsv = mtime("assets/wireframe.js")
        header_tpl = expand_icons(header_tpl, "_partials/header.html")
        footer = expand_icons(footer, "_partials/footer.html")
    except BuildError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    # UI refine done (phase 7): pages declare it so the browser probe stops enforcing grayscale;
    # .w-photo image slots stay grayscale either way
    style = ' data-style="on"' if cfg.get("style") else ""
    # Bricks' default theme mode (Style Manager): the head script falls back to it without "brx_mode"
    if not TOKENS_JSON.is_file():
        print("error: handoff/bricks-tokens.json missing — run python tokens.py", file=sys.stderr)
        return 1
    mode = json.loads(TOKENS_JSON.read_text(encoding="utf-8")).get("styleManager", {}).get("defaultMode", "light")
    if mode not in ("light", "dark", "auto"):
        print(f"error: styleManager.defaultMode {mode!r} must be light, dark or auto (tokens.py)", file=sys.stderr)
        return 1

    lang, i18n = "en", ""
    i18n_file = ROOT / "i18n.json"
    if i18n_file.is_file():
        data = json.loads(i18n_file.read_text(encoding="utf-8"))
        lang = data.pop("lang", "en")
        i18n = "<script>window.WF_I18N=" + json.dumps(data, ensure_ascii=False) + ";</script>\n"

    built = 0
    for frag in sorted(PAGES.glob("*.html")):
        raw = frag.read_text(encoding="utf-8")
        m = META_RE.match(raw)
        if not m:
            print(f"error: {frag.name} missing <!--META {{...}} --> on line 1", file=sys.stderr)
            return 1
        meta = json.loads(m.group(1))
        body = raw[m.end():].strip()
        if final:
            body = REVIEW_RE.sub("", body)
        try:
            body = expand_icons(body, f"_pages/{frag.name}")
        except BuildError as e:
            print(f"error: {e}", file=sys.stderr)
            return 1
        header = (header_tpl
                  .replace("{{WF_TEMPLATE}}", meta.get("template", "—"))
                  .replace("{{WF_FILE}}", frag.name))
        bc = meta.get("body_class", "")
        out = DOC.format(
            lang=lang, style=style, mode=mode, title=esc(meta["title"]), desc=esc(meta.get("desc", "")), css=css,
            nav=meta.get("nav", ""), template=meta.get("template", ""),
            body_class=f' class="{bc}"' if bc else "",
            header=header, body=body, footer=footer, i18n=i18n, jsv=jsv,
        )
        (ROOT / frag.name).write_text(out, encoding="utf-8")
        built += 1
        print(f"built {frag.name}")

    print(f"\n{built} page(s) built into {ROOT}" + (" (final: review blocks stripped)" if final else ""))
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Build standalone wireframe pages.")
    ap.add_argument("--final", action="store_true", help="strip <!--wf:review--> blocks (handoff / client build)")
    raise SystemExit(build(ap.parse_args().final))
